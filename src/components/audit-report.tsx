import { useState } from "react";
import jsPDF from "jspdf";
import { Download, RefreshCw, Loader2 } from "lucide-react";
import type { Report } from "@/lib/analysis";

interface AuditReportProps {
  report: Report;
  onReset: () => void;
}

export function AuditReport({ report, onReset }: AuditReportProps) {
  const [isGenerating, setIsGenerating] = useState(false);

  const handleExportPDF = () => {
    try {
      setIsGenerating(true);

      // 1. Initialisation du document jsPDF (A4)
      const pdf = new jsPDF({
        orientation: "portrait",
        unit: "mm",
        format: "a4",
      });

      // --- STYLES & COULEURS ---
      const primaryColor: [number, number, number] = [15, 23, 42]; // Slate 900
      const accentColor: [number, number, number] = [99, 102, 241]; // Indigo 500
      const textColor: [number, number, number] = [51, 65, 85]; // Slate 700
      const lightBg: [number, number, number] = [248, 250, 252]; // Slate 50

      // --- EN-TÊTE ---
      pdf.setFillColor(...primaryColor);
      pdf.rect(0, 0, 210, 35, "F");

      pdf.setTextColor(255, 255, 255);
      pdf.setFont("helvetica", "bold");
      pdf.setFontSize(22);
      pdf.text("MicCheck AI", 15, 18);

      pdf.setFontSize(10);
      pdf.setFont("helvetica", "normal");
      pdf.text("Voice Quality Audit Report", 15, 26);

      pdf.text(new Date().toLocaleDateString("fr-FR"), 195, 20, { align: "right" });

      // --- DÉTAILS DU FICHIER ---
      let y = 48;
      pdf.setTextColor(...primaryColor);
      pdf.setFont("helvetica", "bold");
      pdf.setFontSize(14);
      pdf.text("Audit Details", 15, y);

      y += 8;
      pdf.setFont("helvetica", "normal");
      pdf.setFontSize(10);
      pdf.setTextColor(...textColor);
      pdf.text(`File Name: ${report.fileName || "Live Recording"}`, 15, y);

      // --- BLOCS DE MÉTRIQUES ---
      y += 15;

      // Card 1 : Loudness (LUFS)
      pdf.setFillColor(...lightBg);
      pdf.roundedRect(15, y, 85, 30, 3, 3, "F");
      pdf.setFont("helvetica", "bold");
      pdf.setFontSize(9);
      pdf.setTextColor(...accentColor);
      pdf.text("LOUDNESS (LUFS)", 22, y + 10);
      pdf.setFontSize(16);
      pdf.setTextColor(...primaryColor);
      pdf.text(`${report.lufs} LUFS`, 22, y + 22);

      // Card 2 : SNR Ratio
      pdf.setFillColor(...lightBg);
      pdf.roundedRect(110, y, 85, 30, 3, 3, "F");
      pdf.setFont("helvetica", "bold");
      pdf.setFontSize(9);
      pdf.setTextColor(...accentColor);
      pdf.text("SNR RATIO", 117, y + 10);
      pdf.setFontSize(16);
      pdf.setTextColor(...primaryColor);
      pdf.text(`${report.snr} dB`, 117, y + 22);

      // --- FOOTER ---
      pdf.setFontSize(8);
      pdf.setTextColor(148, 163, 184);
      pdf.text(
        "Generated by MicCheck AI — Automatic Audio Quality Analyzer",
        105,
        285,
        { align: "center" }
      );

      // 4. Téléchargement immédiat
      pdf.save(`MicCheck_Audit_${Date.now()}.pdf`);

    } catch (error) {
      console.error("Erreur lors de la génération du PDF :", error);
      alert("Erreur lors de la création du PDF.");
    } finally {
      setIsGenerating(false);
    }
  };

  return (
    <div className="space-y-6">
      {/* Zone du rapport affichée à l'écran */}
      <div className="rounded-2xl border border-border bg-card p-6 shadow-xl">
        <h2 className="text-xl font-bold">Voice Audit Summary</h2>
        <p className="text-sm text-muted-foreground">File: {report.fileName}</p>

        <div className="mt-6 grid grid-cols-2 gap-4">
          <div className="rounded-xl border border-border/50 bg-secondary/50 p-4">
            <span className="text-xs text-muted-foreground">Loudness (LUFS)</span>
            <p className="text-lg font-bold">{report.lufs} LUFS</p>
          </div>
          <div className="rounded-xl border border-border/50 bg-secondary/50 p-4">
            <span className="text-xs text-muted-foreground">SNR Ratio</span>
            <p className="text-lg font-bold">{report.snr} dB</p>
          </div>
        </div>
      </div>

      {/* Actions */}
      <div className="flex items-center gap-3">
        <button
          type="button"
          onClick={handleExportPDF}
          disabled={isGenerating}
          className="inline-flex items-center gap-2 rounded-xl bg-gradient-primary px-4 py-2.5 text-sm font-semibold text-primary-foreground shadow-glow transition-transform hover:-translate-y-0.5 cursor-pointer disabled:opacity-50"
        >
          {isGenerating ? (
            <>
              <Loader2 className="size-4 animate-spin" />
              Generating PDF...
            </>
          ) : (
            <>
              <Download className="size-4" />
              Download PDF
            </>
          )}
        </button>

        <button
          type="button"
          onClick={onReset}
          className="inline-flex items-center gap-2 rounded-xl border border-border bg-secondary px-4 py-2.5 text-sm font-semibold text-foreground transition-colors hover:bg-secondary/80 cursor-pointer"
        >
          <RefreshCw className="size-4" />
          New Audit
        </button>
      </div>
    </div>
  );
}
